  `supervisor_id` INT NOT NULL,
  `subject_name` VARCHAR(150) NOT NULL,
  `class_room` VARCHAR(100) NOT NULL,
  `supervision_date` DATE NOT NULL,
  `score` DECIMAL(5,2) DEFAULT NULL,
  `predicate` VARCHAR(50) DEFAULT 'Terjadwal',
  `status` VARCHAR(100) DEFAULT 'Terjadwal',
  `score_planning` DECIMAL(3,2) DEFAULT NULL,
  `score_deep_learning` DECIMAL(3,2) DEFAULT NULL,
  `score_tefa_industry` DECIMAL(3,2) DEFAULT NULL,
  `score_formative_assess` DECIMAL(3,2) DEFAULT NULL,
  `dialogue_notes` TEXT DEFAULT NULL,
  `verified_digital` TINYINT(1) DEFAULT 0,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (`teacher_id`) REFERENCES `teachers` (`id`) ON DELETE CASCADE,
  FOREIGN KEY (`supervisor_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
