  `kktp_threshold` INT NOT NULL DEFAULT 75,
  `server_status` VARCHAR(50) DEFAULT 'Tersinkron CBT-01',
  `last_synced_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
