SET FOREIGN_KEY_CHECKS = 0;
SET SQL_MODE = "NO_AUTO_VALUE_ON_ZERO";
START TRANSACTION;
SET time_zone = "+07:00";

-- ----------------------------------------------------------------------------
-- 1. TABEL PENGGUNA & RBAC (Role-Based Access Control)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `users`;
CREATE TABLE `users` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `nip` VARCHAR(30) UNIQUE NOT NULL,
  `name` VARCHAR(150) NOT NULL,
  `email` VARCHAR(100) UNIQUE NOT NULL,
  `password` VARCHAR(255) NOT NULL,
  `role` ENUM('waka', 'guru', 'kepsek', 'kajur', 'admin') NOT NULL DEFAULT 'guru',
  `avatar_url` VARCHAR(255) DEFAULT NULL,
  `phone_whatsapp` VARCHAR(20) DEFAULT NULL,
  `is_active` TINYINT(1) NOT NULL DEFAULT 1,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 2. TABEL PROGRAM KEAHLIAN / JURUSAN (5 KONSENTRASI KEAHLIAN SMK)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `departments`;
CREATE TABLE `departments` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `code` VARCHAR(20) UNIQUE NOT NULL,
  `name` VARCHAR(150) NOT NULL,
  `head_teacher_id` INT DEFAULT NULL,
  `total_teachers` INT DEFAULT 0,
  `total_classes` INT DEFAULT 6,
  `accreditation` VARCHAR(10) DEFAULT 'A',
  `dudi_partners` TEXT DEFAULT NULL,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 3. TABEL DATA GURU (PEMENUHAN 24 JP & JJMS SERTIFIKASI)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `teachers`;
CREATE TABLE `teachers` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `user_id` INT UNIQUE NOT NULL,
  `nip` VARCHAR(30) UNIQUE NOT NULL,
  `full_name` VARCHAR(150) NOT NULL,
  `department_id` INT DEFAULT NULL,
  `main_subject` VARCHAR(150) NOT NULL,
  `assigned_classes` VARCHAR(150) DEFAULT NULL,
  `weekly_hours` INT NOT NULL DEFAULT 24,
  `certification_status` ENUM('certified', 'process', 'uncertified') DEFAULT 'certified',
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE,
  FOREIGN KEY (`department_id`) REFERENCES `departments` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 4. TABEL TAHUN AJARAN & KALENDER AKADEMIK
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `academic_years`;
CREATE TABLE `academic_years` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `name` VARCHAR(50) NOT NULL,
  `semester` ENUM('Ganjil', 'Genap') NOT NULL,
  `is_active` TINYINT(1) NOT NULL DEFAULT 1,
  `start_date` DATE NOT NULL,
  `end_date` DATE NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 5. TABEL VERIFIKASI PERANGKAT AJAR GURU (MODUL 6.4)
-- Modul Ajar, ATP, Prota, Prosem (Standar Proses Permendikdasmen No. 1/2026)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `teacher_documents`;
CREATE TABLE `teacher_documents` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `teacher_id` INT NOT NULL,
  `academic_year_id` INT NOT NULL,
  `doc_type` ENUM('modul_ajar', 'atp', 'prota', 'prosem') NOT NULL,
  `file_name` VARCHAR(255) DEFAULT NULL,
  `file_path` VARCHAR(255) DEFAULT NULL,
  `file_size_kb` INT DEFAULT NULL,
  `status` ENUM('approved', 'review', 'revision', 'missing') NOT NULL DEFAULT 'missing',
  `score` DECIMAL(5,2) DEFAULT NULL,
  `review_notes` TEXT DEFAULT NULL,
  `uploaded_at` DATETIME DEFAULT NULL,
  `verified_at` DATETIME DEFAULT NULL,
  `verified_by` INT DEFAULT NULL,
  FOREIGN KEY (`teacher_id`) REFERENCES `teachers` (`id`) ON DELETE CASCADE,
  FOREIGN KEY (`academic_year_id`) REFERENCES `academic_years` (`id`) ON DELETE CASCADE,
  FOREIGN KEY (`verified_by`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  UNIQUE KEY `unique_teacher_doc` (`teacher_id`, `academic_year_id`, `doc_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 6. TABEL JURNAL MENGAJAR HARIAN GURU (MODUL 6.5)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `teaching_journals`;
CREATE TABLE `teaching_journals` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `teacher_id` INT NOT NULL,
  `subject_name` VARCHAR(150) NOT NULL,
  `class_room` VARCHAR(50) NOT NULL,
  `journal_date` DATE NOT NULL,
  `period_start` INT NOT NULL,
  `period_end` INT NOT NULL,
  `students_present` INT NOT NULL,
  `students_absent` INT NOT NULL DEFAULT 0,
  `learning_material` TEXT NOT NULL,
  `deep_learning_focus` VARCHAR(150) DEFAULT NULL,
  `photo_evidence_url` VARCHAR(255) DEFAULT NULL,
  `status` ENUM('submitted', 'verified') DEFAULT 'verified',
  `submitted_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (`teacher_id`) REFERENCES `teachers` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 7. TABEL JADWAL PELAJARAN & PTM ANTI-BENTROK (MODUL 6.3)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `schedule_slots`;
CREATE TABLE `schedule_slots` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `academic_year_id` INT NOT NULL,
  `department_id` INT NOT NULL,
  `day_name` ENUM('Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat') NOT NULL,
  `period_start` INT NOT NULL,
  `period_end` INT NOT NULL,
  `class_name` VARCHAR(50) NOT NULL,
  `subject_name` VARCHAR(150) NOT NULL,
  `category` ENUM('Kejuruan', 'Nasional', 'Dasar', 'P5') NOT NULL DEFAULT 'Kejuruan',
  `teacher_id` INT NOT NULL,
  `room_lab_name` VARCHAR(100) NOT NULL,
  `is_conflict` TINYINT(1) DEFAULT 0,
  FOREIGN KEY (`academic_year_id`) REFERENCES `academic_years` (`id`) ON DELETE CASCADE,
  FOREIGN KEY (`department_id`) REFERENCES `departments` (`id`) ON DELETE CASCADE,
  FOREIGN KEY (`teacher_id`) REFERENCES `teachers` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 8. TABEL MONITORING PRAKTIK KERJA LAPANGAN (PKL) & DUDI (MODUL 6.8)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `pkl_placements`;
CREATE TABLE `pkl_placements` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `academic_year_id` INT NOT NULL,
  `student_nisn` VARCHAR(20) UNIQUE NOT NULL,
  `student_name` VARCHAR(150) NOT NULL,
  `rombel` VARCHAR(50) NOT NULL,
  `department_id` INT NOT NULL,
  `company_name` VARCHAR(200) NOT NULL,
  `company_tier` VARCHAR(100) DEFAULT 'Tier-1 Industri',
  `company_city` VARCHAR(100) DEFAULT 'Banjarmasin',
  `school_mentor_id` INT NOT NULL,
  `dudi_mentor_name` VARCHAR(150) NOT NULL,
  `dudi_mentor_phone` VARCHAR(30) DEFAULT NULL,
  `duration_months` INT DEFAULT 6,
  `current_month` INT DEFAULT 3,
  `progress_pct` INT DEFAULT 50,
  `logbook_verified_pct` INT DEFAULT 95,
  `status` ENUM('Sedang Magang', 'Butuh Monitoring', 'Logbook Tertunda', 'Selesai') DEFAULT 'Sedang Magang',
  `needs_monitoring` TINYINT(1) DEFAULT 0,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (`academic_year_id`) REFERENCES `academic_years` (`id`) ON DELETE CASCADE,
  FOREIGN KEY (`department_id`) REFERENCES `departments` (`id`) ON DELETE CASCADE,
  FOREIGN KEY (`school_mentor_id`) REFERENCES `teachers` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 9. TABEL UJI KOMPETENSI KEAHLIAN (UKK) & LISENSI LSP-P1 (MODUL 6.9)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `ukk_schemes`;
CREATE TABLE `ukk_schemes` (
  `id` INT AUTO_INCREMENT PRIMARY KEY,
  `academic_year_id` INT NOT NULL,
  `code` VARCHAR(50) UNIQUE NOT NULL,
  `title` VARCHAR(200) NOT NULL,
  `department_id` INT NOT NULL,
  `track_type` ENUM('lsp', 'mandiri') NOT NULL DEFAULT 'lsp',
  `certificate_name` VARCHAR(150) NOT NULL,
  `tuk_location` VARCHAR(200) NOT NULL,
  `assessor_info` TEXT NOT NULL,
  `candidate_count` INT NOT NULL DEFAULT 72,
  `sessions_info` VARCHAR(100) NOT NULL,
  `schedule_date` VARCHAR(100) NOT NULL,
  `tuk_status` VARCHAR(50) DEFAULT 'TUK & Perangkat Siap',
  FOREIGN KEY (`academic_year_id`) REFERENCES `academic_years` (`id`) ON DELETE CASCADE,
  FOREIGN KEY (`department_id`) REFERENCES `departments` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ----------------------------------------------------------------------------
-- 10. TABEL SUPERVISI AKADEMIK GURU (MODUL 6.6)
-- Rubrik 4 Komponen Permendikdasmen No. 1/2026
