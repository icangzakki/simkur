-- ----------------------------------------------------------------------------
-- 12. TABEL AUDIT LOG KEAMANAN (KEPATUHAN UU PDP NO. 27/2022)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `security_audit_logs`;
