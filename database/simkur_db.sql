-- ----------------------------------------------------------------------------
-- 14. TABEL PRESENSI & ABSENSI SISWA HARIAN (ROLL-CALL KBM)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS `student_attendances`;
CREATE TABLE `student_attendances` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `student_id` INT NOT NULL,
  `journal_id` INT DEFAULT NULL,
  `rombel_class` VARCHAR(50) NOT NULL,
  `attendance_date` DATE NOT NULL,
  `status` ENUM('H', 'S', 'I', 'A') NOT NULL DEFAULT 'H',
  `notes` VARCHAR(255) DEFAULT NULL,
  `recorded_by` INT DEFAULT NULL,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (`student_id`) REFERENCES `students` (`id`) ON DELETE CASCADE,
  FOREIGN KEY (`journal_id`) REFERENCES `teaching_journals` (`id`) ON DELETE SET NULL,
  FOREIGN KEY (`recorded_by`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  UNIQUE KEY `unique_student_date` (`student_id`, `attendance_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


